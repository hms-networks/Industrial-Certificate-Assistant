"""HiveMQ broker TLS / mutual-TLS deployment package.

HiveMQ is a Java broker: it reads its identity from a PKCS#12 keystore and,
for mutual TLS, trusts client certificates from a PKCS#12 truststore. It does
not read PEM files. The keystore password is never written to the package;
config.xml references it through an environment variable instead.
"""

from __future__ import annotations

from pathlib import Path


HIVEMQ_PORT = 8883
PASSWORD_ENV = "HIVEMQ_TLS_KEYSTORE_PASSWORD"
DEFAULT_TLS_DIR = "/opt/hivemq/conf/ica-tls"
KEYSTORE_NAME = "hivemq-keystore.p12"
TRUSTSTORE_NAME = "hivemq-truststore.p12"
BLOCK_BEGIN = "<!-- BEGIN Industrial Certificate Assistant TLS listener -->"
BLOCK_END = "<!-- END Industrial Certificate Assistant TLS listener -->"


def render_hivemq_config(mutual_tls: bool, port: int = HIVEMQ_PORT) -> str:
    password = "${ENV:" + PASSWORD_ENV + "}"
    truststore = ""
    if mutual_tls:
        truststore = (
            "                    <truststore>\n"
            f"                        <path>{DEFAULT_TLS_DIR}/{TRUSTSTORE_NAME}</path>\n"
            f"                        <password>{password}</password>\n"
            "                    </truststore>\n"
        )
    mode = "REQUIRED" if mutual_tls else "NONE"
    return (
        '<?xml version="1.0"?>\n'
        "<!--\n"
        "  HiveMQ TLS listener generated by Industrial Certificate Assistant.\n"
        f"  Mutual TLS: {'enabled (client certificate REQUIRED)' if mutual_tls else 'disabled (server-authenticated TLS only)'}\n"
        "\n"
        "  Container deployments can mount this file as /opt/hivemq/conf/config.xml.\n"
        "  install-hivemq-tls.sh merges only the marked listener block into an\n"
        "  existing config.xml and leaves the other listeners untouched.\n"
        "\n"
        f"  The keystore password is read from the {PASSWORD_ENV}\n"
        "  environment variable and is intentionally not stored in this file.\n"
        "-->\n"
        "<hivemq>\n"
        "    <listeners>\n"
        f"        {BLOCK_BEGIN}\n"
        "        <tls-tcp-listener>\n"
        f"            <port>{port}</port>\n"
        "            <bind-address>0.0.0.0</bind-address>\n"
        "            <name>ica-mqtt-tls</name>\n"
        "            <tls>\n"
        "                    <keystore>\n"
        f"                        <path>{DEFAULT_TLS_DIR}/{KEYSTORE_NAME}</path>\n"
        f"                        <password>{password}</password>\n"
        f"                        <private-key-password>{password}</private-key-password>\n"
        "                    </keystore>\n"
        f"{truststore}"
        "                    <protocols>\n"
        "                        <protocol>TLSv1.3</protocol>\n"
        "                        <protocol>TLSv1.2</protocol>\n"
        "                    </protocols>\n"
        f"                    <client-authentication-mode>{mode}</client-authentication-mode>\n"
        "            </tls>\n"
        "        </tls-tcp-listener>\n"
        f"        {BLOCK_END}\n"
        "    </listeners>\n"
        "</hivemq>\n"
    )


INSTALL_SCRIPT = r'''#!/usr/bin/env bash
# Installs the ICA HiveMQ TLS listener on a systemd-managed HiveMQ host.
# Container deployments: see the package README.txt instead.
set -Eeuo pipefail

HIVEMQ_HOME=${HIVEMQ_HOME:-/opt/hivemq}
SERVICE=${HIVEMQ_SERVICE:-hivemq.service}
CONFIG="$HIVEMQ_HOME/conf/config.xml"
TLS_DIR="$HIVEMQ_HOME/conf/ica-tls"
ENV_FILE=${HIVEMQ_ENV_FILE:-/etc/hivemq/ica-tls.env}
DROPIN_DIR="/etc/systemd/system/${SERVICE}.d"
DROPIN="$DROPIN_DIR/ica-tls.conf"
BACKUP_ROOT=${HIVEMQ_BACKUP_ROOT:-/var/backups/industrial-certificate-assistant}
PORT=@PORT@
MUTUAL_TLS=@MUTUAL_TLS@
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
PACKAGE_CONFIG="$HERE/hivemq-config.xml"
KEYSTORE="$HERE/@KEYSTORE@"
TRUSTSTORE="$HERE/@TRUSTSTORE@"
CERTIFICATE="$HERE/broker-certificate.pem"
BEGIN_MARK='@BLOCK_BEGIN@'
END_MARK='@BLOCK_END@'
CHANGED=0
BACKUP=""
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

fail() {
    printf 'ERROR: %s\n' "$*" >&2
    if (( CHANGED )) && [[ -n "$BACKUP" && -x "$BACKUP/rollback.sh" ]]; then
        printf 'Restoring the previous HiveMQ configuration...\n' >&2
        CHANGED=0
        "$BACKUP/rollback.sh" || true
    fi
    exit 1
}
require() { command -v "$1" >/dev/null 2>&1 || fail "Required command not found: $1"; }

(( EUID == 0 )) || fail "Run this installer with sudo."
for command in openssl systemctl awk sed grep install sha256sum stat timeout mktemp; do
    require "$command"
done
[[ -f "$CONFIG" ]] || fail "HiveMQ config.xml not found: $CONFIG (set HIVEMQ_HOME)."
[[ -f "$PACKAGE_CONFIG" ]] || fail "Missing package file: $PACKAGE_CONFIG"
[[ -f "$KEYSTORE" ]] || fail "Missing package file: $KEYSTORE"
[[ -f "$CERTIFICATE" ]] || fail "Missing package file: $CERTIFICATE"
if (( MUTUAL_TLS )); then
    [[ -f "$TRUSTSTORE" ]] || fail "Missing package file: $TRUSTSTORE"
fi

SERVICE_USER=$(systemctl show -p User --value "$SERVICE" 2>/dev/null || true)
SERVICE_USER=${SERVICE_USER:-hivemq}
id "$SERVICE_USER" >/dev/null 2>&1 || fail "HiveMQ service user not found: $SERVICE_USER (set HIVEMQ_SERVICE)."
SERVICE_GROUP=$(id -gn "$SERVICE_USER")
# config.xml keeps its current owner and mode (HiveMQ installs are often
# owned by the service user); only its listener block changes.
CONFIG_UID=$(stat -c %u "$CONFIG")
CONFIG_GID=$(stat -c %g "$CONFIG")
CONFIG_MODE=$(stat -c %a "$CONFIG")

read -r -s -p "Keystore password chosen when this package was issued: " STORE_PASSWORD
printf '\n'
[[ -n "$STORE_PASSWORD" ]] || fail "A keystore password is required."
[[ "$STORE_PASSWORD" != *$'\n'* && "$STORE_PASSWORD" != *'"'* && "$STORE_PASSWORD" != *'\'* ]] \
    || fail "The keystore password cannot contain newlines, double quotes, or backslashes."
printf '%s' "$STORE_PASSWORD" >"$WORK/pass"
chmod 0600 "$WORK/pass"

# Validate the package before anything on the host is changed.
openssl pkcs12 -in "$KEYSTORE" -passin "file:$WORK/pass" -nokeys -clcerts -out "$WORK/keystore-leaf.pem" 2>"$WORK/err" \
    || { cat "$WORK/err" >&2; fail "Cannot open $KEYSTORE with that password."; }
openssl pkcs12 -in "$KEYSTORE" -passin "file:$WORK/pass" -nocerts -nodes 2>/dev/null \
    | openssl pkey -pubout -outform DER 2>/dev/null | sha256sum | awk '{print $1}' >"$WORK/key-hash"
openssl x509 -in "$CERTIFICATE" -pubkey -noout | openssl pkey -pubin -outform DER 2>/dev/null \
    | sha256sum | awk '{print $1}' >"$WORK/cert-hash"
cmp -s "$WORK/key-hash" "$WORK/cert-hash" || fail "The keystore private key does not match broker-certificate.pem."
EXPECTED_HASH=$(openssl x509 -in "$CERTIFICATE" -outform DER | sha256sum | awk '{print $1}')
KEYSTORE_HASH=$(openssl x509 -in "$WORK/keystore-leaf.pem" -outform DER | sha256sum | awk '{print $1}')
[[ "$EXPECTED_HASH" == "$KEYSTORE_HASH" ]] || fail "The keystore certificate is not broker-certificate.pem."
if (( MUTUAL_TLS )); then
    openssl pkcs12 -in "$TRUSTSTORE" -passin "file:$WORK/pass" -nokeys -out /dev/null 2>"$WORK/err" \
        || { cat "$WORK/err" >&2; fail "Cannot open $TRUSTSTORE with that password."; }
fi
if command -v keytool >/dev/null 2>&1; then
    keytool -list -storetype PKCS12 -keystore "$KEYSTORE" -storepass:file "$WORK/pass" | grep -q PrivateKeyEntry \
        || fail "Java does not see a private key entry in $KEYSTORE."
    if (( MUTUAL_TLS )); then
        keytool -list -storetype PKCS12 -keystore "$TRUSTSTORE" -storepass:file "$WORK/pass" | grep -q trustedCertEntry \
            || fail "Java does not see trusted CA entries in $TRUSTSTORE."
    fi
fi

# Build the merged config.xml: drop any previous ICA block, then insert the
# new block before </listeners>. Other listeners are left exactly as they are.
sed -n "/$BEGIN_MARK/,/$END_MARK/p" "$PACKAGE_CONFIG" \
    | sed "s#@DEFAULT_TLS_DIR@#$TLS_DIR#g" >"$WORK/block.xml"
grep -q "tls-tcp-listener" "$WORK/block.xml" || fail "No ICA listener block found in $PACKAGE_CONFIG."
awk -v begin="$BEGIN_MARK" -v end="$END_MARK" '
    index($0, begin) { skip=1; next }
    skip && index($0, end) { skip=0; next }
    !skip { print }
' "$CONFIG" >"$WORK/config-without-ica.xml"
if grep -Eq "<port>[[:space:]]*$PORT[[:space:]]*</port>" "$WORK/config-without-ica.xml"; then
    fail "config.xml already has a listener on port $PORT that ICA did not create. Remove or move it, then rerun."
fi
awk -v block="$WORK/block.xml" '
    /<\/listeners>/ && !done {
        while ((getline line < block) > 0) print line
        done=1
    }
    { print }
    END { if (!done) exit 3 }
' "$WORK/config-without-ica.xml" >"$WORK/config.xml" \
    || fail "Could not find a </listeners> line in $CONFIG. Merge hivemq-config.xml manually."
if command -v xmllint >/dev/null 2>&1 && [[ -f "$HIVEMQ_HOME/conf/config.xsd" ]]; then
    xmllint --noout --schema "$HIVEMQ_HOME/conf/config.xsd" "$WORK/config.xml" \
        || fail "The merged config.xml does not validate against config.xsd."
fi

printf '\nHiveMQ home:   %s\nService:       %s (user %s)\n' "$HIVEMQ_HOME" "$SERVICE" "$SERVICE_USER"
printf 'Listener:      TLS on TCP %s, mutual TLS %s\n' "$PORT" "$( (( MUTUAL_TLS )) && echo REQUIRED || echo disabled )"
printf 'Stores:        %s\nPassword file: %s (root-only, loaded by systemd)\n\n' "$TLS_DIR" "$ENV_FILE"
read -r -p "Type INSTALL to back up the current configuration, install TLS, and restart HiveMQ: " answer
[[ "$answer" == "INSTALL" ]] || fail "Installation cancelled; no files were changed."

BACKUP="$BACKUP_ROOT/hivemq-$(date +%Y%m%d-%H%M%S)"
install -d -m 0700 "$BACKUP"
install -m 0600 "$CONFIG" "$BACKUP/config.xml"
[[ -d "$TLS_DIR" ]] && cp -a "$TLS_DIR" "$BACKUP/ica-tls"
[[ -f "$ENV_FILE" ]] && cp -a "$ENV_FILE" "$BACKUP/ica-tls.env"
[[ -f "$DROPIN" ]] && cp -a "$DROPIN" "$BACKUP/ica-tls.conf"

cat >"$BACKUP/rollback.sh" <<EOF
#!/usr/bin/env bash
set -Eeuo pipefail
if (( EUID != 0 )); then echo "Run with sudo." >&2; exit 1; fi
install -m "$CONFIG_MODE" -o "$CONFIG_UID" -g "$CONFIG_GID" "$BACKUP/config.xml" "$CONFIG"
rm -rf "$TLS_DIR"
if [[ -d "$BACKUP/ica-tls" ]]; then cp -a "$BACKUP/ica-tls" "$TLS_DIR"; fi
if [[ -f "$BACKUP/ica-tls.env" ]]; then cp -a "$BACKUP/ica-tls.env" "$ENV_FILE"; else rm -f "$ENV_FILE"; fi
if [[ -f "$BACKUP/ica-tls.conf" ]]; then cp -a "$BACKUP/ica-tls.conf" "$DROPIN"; else rm -f "$DROPIN"; fi
systemctl daemon-reload
systemctl restart "$SERVICE"
systemctl --no-pager --full status "$SERVICE" || true
EOF
chmod 0700 "$BACKUP/rollback.sh"

rollback_on_error() {
    exit_code=$1
    trap - ERR
    printf '\nERROR: command failed at line %s: %s\n' "$2" "$3" >&2
    if (( CHANGED )); then
        printf 'Installation failed; restoring the previous HiveMQ configuration...\n' >&2
        "$BACKUP/rollback.sh" || true
    fi
    exit "$exit_code"
}
trap 'rollback_on_error "$?" "$LINENO" "$BASH_COMMAND"' ERR

CHANGED=1
install -d -m 0750 -o root -g "$SERVICE_GROUP" "$TLS_DIR"
install -m 0640 -o root -g "$SERVICE_GROUP" "$KEYSTORE" "$TLS_DIR/@KEYSTORE@"
if (( MUTUAL_TLS )); then
    install -m 0640 -o root -g "$SERVICE_GROUP" "$TRUSTSTORE" "$TLS_DIR/@TRUSTSTORE@"
else
    rm -f "$TLS_DIR/@TRUSTSTORE@"
fi
install -d -m 0755 "$(dirname -- "$ENV_FILE")"
( umask 077; printf '@PASSWORD_ENV@="%s"\n' "$STORE_PASSWORD" >"$ENV_FILE" )
install -d -m 0755 "$DROPIN_DIR"
printf '[Service]\nEnvironmentFile=%s\n' "$ENV_FILE" >"$DROPIN"
chmod 0644 "$DROPIN"
install -m "$CONFIG_MODE" -o "$CONFIG_UID" -g "$CONFIG_GID" "$WORK/config.xml" "$CONFIG"

systemctl daemon-reload
systemctl restart "$SERVICE"

SERVED=0
for attempt in {1..60}; do
    if timeout 3 openssl s_client -connect "127.0.0.1:$PORT" -servername localhost -showcerts \
            </dev/null >"$WORK/served.txt" 2>&1 && \
            openssl x509 -in "$WORK/served.txt" -noout >/dev/null 2>&1; then
        SERVED=1
        break
    fi
    # With client authentication REQUIRED, s_client may exit non-zero after
    # the server certificate has already been received; accept that too.
    if openssl x509 -in "$WORK/served.txt" -noout >/dev/null 2>&1; then
        SERVED=1
        break
    fi
    sleep 1
done
(( SERVED )) || fail "HiveMQ did not present a certificate on TCP $PORT within 60 seconds. Check: journalctl -u $SERVICE and $HIVEMQ_HOME/log/hivemq.log"
SERVED_HASH=$(openssl x509 -in "$WORK/served.txt" -outform DER | sha256sum | awk '{print $1}')
[[ "$SERVED_HASH" == "$EXPECTED_HASH" ]] || fail "HiveMQ is not presenting the deployed broker certificate on TCP $PORT."

CHANGED=0
trap - ERR
printf '\nHiveMQ TLS installation succeeded.\n'
openssl x509 -in "$WORK/served.txt" -noout -subject -issuer -dates -fingerprint -sha256 -ext subjectAltName
printf '\nBackup and rollback script: %s\n' "$BACKUP/rollback.sh"
printf 'Next, from a client machine: trust/verify-hivemq-tls.sh <broker-dns-or-ip> %s <client-certificate.pem> <client-private-key.pem>\n' "$PORT"
'''


VERIFY_SCRIPT = r'''#!/usr/bin/env bash
# Verifies the HiveMQ TLS listener from any machine that trusts this PKI.
# Sends a raw MQTT 3.1.1 CONNECT over TLS and checks for a CONNACK, so only
# openssl is required on the test machine.
set -uo pipefail

if [[ $# -lt 1 ]]; then
    echo "Usage: $0 <broker-dns-or-ip> [port] [client-certificate.pem client-private-key.pem]" >&2
    exit 2
fi
HOST=$1
PORT=${2:-@PORT@}
CLIENT_CERT=${3:-}
CLIENT_KEY=${4:-}
MUTUAL_TLS=@MUTUAL_TLS@
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
CAFILE="$HERE/root-ca.pem"
FAILURES=0
command -v openssl >/dev/null 2>&1 || { echo "openssl is required." >&2; exit 2; }
command -v od >/dev/null 2>&1 || { echo "od is required." >&2; exit 2; }
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if [[ $HOST =~ ^[0-9.]+$ || $HOST == *:* ]]; then
    NAME_CHECK=( -verify_ip "$HOST" )
else
    NAME_CHECK=( -verify_hostname "$HOST" -servername "$HOST" )
fi

# MQTT 3.1.1 CONNECT, clean session, keep-alive 60 s, client ID "ica-verify".
printf '\x10\x16\x00\x04MQTT\x04\x02\x00\x3c\x00\x0aica-verify' >"$WORK/connect.bin"

mqtt_connect() {  # $@: extra s_client arguments; prints the CONNACK bytes, if any
    { cat "$WORK/connect.bin"; sleep 3; } | timeout 8 openssl s_client -quiet -connect "$HOST:$PORT" \
        -CAfile "$CAFILE" -verify_return_error "${NAME_CHECK[@]}" "$@" 2>>"$WORK/sclient.err" \
        | head -c 4 | od -An -tx1 | tr -d ' \n'
}

pass() { printf 'PASS  %s\n' "$*"; }
failed() { printf 'FAIL  %s\n' "$*"; FAILURES=$((FAILURES + 1)); }

echo "== Server certificate presented by $HOST:$PORT"
timeout 8 openssl s_client -connect "$HOST:$PORT" -CAfile "$CAFILE" "${NAME_CHECK[@]}" -showcerts \
    </dev/null >"$WORK/handshake.txt" 2>&1
if openssl x509 -in "$WORK/handshake.txt" -noout >/dev/null 2>&1; then
    openssl x509 -in "$WORK/handshake.txt" -noout -subject -issuer -dates -ext subjectAltName
else
    failed "No certificate received from $HOST:$PORT (listener down, port blocked, or name does not resolve)"
    exit 1
fi
if grep -q "Verify return code: 0 (ok)" "$WORK/handshake.txt"; then
    pass "Broker certificate chains to root-ca.pem and matches $HOST"
else
    failed "Broker certificate verification: $(grep 'Verify return code' "$WORK/handshake.txt" | head -n 1)"
    echo "      The remaining checks cannot run until the broker certificate verifies."
    echo
    echo "$FAILURES check(s) failed."
    exit 1
fi

echo
echo "== MQTT CONNECT without a client certificate"
reply=$(mqtt_connect)
if (( MUTUAL_TLS )); then
    if [[ $reply == 2002* ]]; then
        failed "Broker accepted a client with no certificate; mutual TLS is not being enforced"
    else
        pass "Broker rejected a client with no certificate"
    fi
elif [[ $reply == 20020000 ]]; then
    pass "Broker accepted the MQTT connection (CONNACK 0x00)"
else
    failed "No successful CONNACK received (got '${reply:-nothing}')"
fi

if [[ -n "$CLIENT_CERT" && -n "$CLIENT_KEY" ]]; then
    echo
    echo "== MQTT CONNECT with client certificate $(basename -- "$CLIENT_CERT")"
    if grep -qE 'ENCRYPTED PRIVATE KEY|Proc-Type: 4,ENCRYPTED' "$CLIENT_KEY"; then
        read -r -s -p "Client private-key password: " key_password; printf '\n'
        printf '%s' "$key_password" >"$WORK/keypass"; chmod 0600 "$WORK/keypass"
        reply=$(mqtt_connect -cert "$CLIENT_CERT" -key "$CLIENT_KEY" -pass "file:$WORK/keypass")
    else
        reply=$(mqtt_connect -cert "$CLIENT_CERT" -key "$CLIENT_KEY")
    fi
    if [[ $reply == 20020000 ]]; then
        pass "Broker accepted the client certificate (CONNACK 0x00)"
    else
        failed "Client certificate connection did not receive CONNACK 0x00 (got '${reply:-nothing}')"
        tail -n 5 "$WORK/sclient.err" >&2
    fi
elif (( MUTUAL_TLS )); then
    echo
    echo "NOTE  Pass a client certificate and key to test a positive mutual-TLS connection."
fi

echo
if (( FAILURES )); then
    echo "$FAILURES check(s) failed."
    exit 1
fi
echo "All checks passed."
'''


def readme_details(mutual_tls: bool, port: int = HIVEMQ_PORT) -> str:
    mode = "REQUIRED (mutual TLS)" if mutual_tls else "NONE (server-authenticated TLS only)"
    truststore_mount = (
        f"      -v \"$PWD/{TRUSTSTORE_NAME}:{DEFAULT_TLS_DIR}/{TRUSTSTORE_NAME}:ro\" \\\n"
        if mutual_tls else ""
    )
    text = f"""HIVEMQ DETAILS

Listener: TLS on TCP {port}
Client authentication: {mode}

The .p12 files are protected by the keystore password chosen at issuance.
ICA does not store that password. HiveMQ reads it from the environment
variable {PASSWORD_ENV}. The PEM files in deploy/ are the same identity for
inspection and non-Java tooling; HiveMQ itself uses only the .p12 files.


1. Linux host with HiveMQ under systemd (/opt/hivemq, hivemq.service)

  Copy deploy/ to the broker host, then run inside it:

    sudo ./install-hivemq-tls.sh

  The installer validates the keystores against broker-certificate.pem,
  asks for the keystore password and typed confirmation, backs up
  config.xml, merges only the marked ICA listener block, stores the
  password in a root-only systemd EnvironmentFile, restarts HiveMQ, and
  confirms the served certificate. Every run writes a rollback.sh into
  /var/backups/industrial-certificate-assistant/.

  Overrides: HIVEMQ_HOME, HIVEMQ_SERVICE, HIVEMQ_ENV_FILE, HIVEMQ_BACKUP_ROOT.


2. Docker / Podman (hivemq/hivemq-ce or hivemq/hivemq4)

  Run from the deploy/ folder. The password is read from a prompt, not
  typed on the command line:

    read -rs -p "Keystore password: " {PASSWORD_ENV}; export {PASSWORD_ENV}
    docker run -d --name hivemq -p {port}:{port} \\
      -e {PASSWORD_ENV} \\
      -v "$PWD/hivemq-config.xml:/opt/hivemq/conf/config.xml:ro" \\
      -v "$PWD/{KEYSTORE_NAME}:{DEFAULT_TLS_DIR}/{KEYSTORE_NAME}:ro" \\
{truststore_mount}      hivemq/hivemq-ce

  hivemq-config.xml contains only the TLS listener, so the image's plain
  TCP 1883 listener is not enabled. On SELinux hosts add ,Z to each -v
  option (or ,z if several containers share the files).


3. Verify

  From a machine that can reach the broker:

    trust/verify-hivemq-tls.sh <broker-dns-or-ip> {port} client-certificate.pem client-private-key.pem

  The host must match a DNS/IP SAN in the broker certificate.
"""
    if mutual_tls:
        text += """  With mutual TLS the script checks both that a client with no certificate
  is rejected and that the supplied client certificate is accepted.


4. Client certificates

  Issue each device with the "MQTT Client/Device" profile in the same ICA
  project; its package's deploy/ folder has everything the device needs.
  HiveMQ rejects clients whose certificate does not chain to this PKI or
  lacks the clientAuth extended key usage.

  Important: HiveMQ Community Edition only checks that the certificate is
  valid. It does not tie the MQTT Client ID or topic permissions to the
  certificate. After TLS, the bundled allow-all extension accepts any
  client that presented a valid certificate. To authorize per certificate
  (for example CN = Client ID), use the HiveMQ Enterprise Security
  Extension or a custom authentication extension.
"""
    else:
        text += """
  Mutual TLS is disabled: any client that trusts root-ca.pem can connect
  at the TLS layer. MQTT authentication is up to HiveMQ extensions.
"""
    return text + f"""

Security notes
  - Root and intermediate CA private keys are never included in this package.
  - Keep TCP 1883 closed to untrusted networks. Only expose {port}.
  - HiveMQ reads keystores at startup; restart it after every reissue.
"""


def write_hivemq_bundle(destination: Path, mutual_tls: bool, port: int = HIVEMQ_PORT) -> dict[str, Path]:
    replacements = {
        "@PORT@": str(port),
        "@MUTUAL_TLS@": "1" if mutual_tls else "0",
        "@KEYSTORE@": KEYSTORE_NAME,
        "@TRUSTSTORE@": TRUSTSTORE_NAME,
        "@BLOCK_BEGIN@": BLOCK_BEGIN,
        "@BLOCK_END@": BLOCK_END,
        "@PASSWORD_ENV@": PASSWORD_ENV,
        "@DEFAULT_TLS_DIR@": DEFAULT_TLS_DIR,
    }

    def render(template: str) -> str:
        for token, value in replacements.items():
            template = template.replace(token, value)
        return template

    files = {
        "hivemq_config": destination / "hivemq-config.xml",
        "hivemq_install": destination / "install-hivemq-tls.sh",
        "hivemq_verify": destination / "verify-hivemq-tls.sh",
    }
    files["hivemq_config"].write_text(render_hivemq_config(mutual_tls, port), encoding="utf-8", newline="\n")
    files["hivemq_install"].write_text(render(INSTALL_SCRIPT), encoding="utf-8", newline="\n")
    files["hivemq_verify"].write_text(render(VERIFY_SCRIPT), encoding="utf-8", newline="\n")
    files["hivemq_install"].chmod(0o755)
    files["hivemq_verify"].chmod(0o755)
    return files
